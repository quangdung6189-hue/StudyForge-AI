import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { chromium } from 'playwright';

const base = process.env.EXAM_STUDIO_TEST_URL;
if (!base || !['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Set EXAM_STUDIO_TEST_URL to an isolated local server.');
const directory = path.resolve('.data/exam-review-browser'); await mkdir(directory, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const checks = [], errors = [], pass = name => { checks.push(name); console.log('PASS: ' + name); };
let page;
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1100 } });
  const registered = await context.request.post(base + '/api/auth/register', { data: { email: `review-${randomUUID()}@example.com`, password: 'ReviewSecurePass123!', name: 'Review Teacher', role: 'teacher' } });
  assert.equal(registered.status(), 200);
  page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/quizzes/create', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Mở trình biên soạn · Không cần tài liệu →', exact: true }).click();
  const title = page.getByPlaceholder('Ví dụ: Kiểm tra giữa kỳ · Tin học 10'), code = page.getByRole('textbox', { name: 'Văn bản đề thi', exact: true });
  await title.fill('Đề đối chiếu đáp án tự luận');
  const fixture = 'PHẦN I. TRẢ LỜI NGẮN\nCâu 1: Tên gọi máy tính?\nTrả lời: ENIAC\nPHẦN II. TỰ LUẬN\nCâu 4: Trình bày nhược điểm của thế hệ máy tính đầu tiên.\nTrả lời:\n- Máy tính rất lớn.\n- Máy tính đắt tiền.\n- Tiêu thụ nhiều điện.';
  await code.fill(fixture);
  const essay = page.locator('.exam-card').nth(1);
  assert.equal(await page.getByLabel('Dạng câu 2', { exact: true }).inputValue(), 'essay');
  await essay.getByText('Đã có đáp án mẫu', { exact: true }).waitFor();
  assert.equal(await essay.getByText('Thiếu đáp án', { exact: true }).count(), 0);
  assert((await page.getByLabel('Đáp án câu 2', { exact: true }).inputValue()).includes('\n- Máy tính đắt tiền.'));
  const answerHeight = await page.getByLabel('Đáp án câu 2', { exact: true }).evaluate(ta => ta.clientHeight);
  assert(answerHeight >= 72, `Multiline answer height: ${answerHeight}`);
  pass('Answered essay shows manual grading and complete multiline model answer, never a missing key');
  await page.getByLabel('Điểm câu 2', { exact: true }).fill('2');
  assert(!(await code.inputValue()).includes('[Cần xác minh]'));
  await page.getByRole('button', { name: 'Kiểm tra & duyệt đề →', exact: true }).click();
  const summary = page.getByRole('alert', { name: 'Kết quả kiểm tra đề', exact: true });
  await summary.waitFor(); await summary.locator('li[data-status="manual"]').waitFor();
  assert.equal(await summary.getByText('Thiếu đáp án', { exact: true }).count(), 0);
  await summary.getByRole('button', { name: /Câu 4/ }).focus(); await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.activeElement?.classList.contains('exam-card'));
  pass('Prepare explains actual manual blocker and keyboard summary link focuses the right question');
  await code.fill(fixture.replace('đầu tiên.', 'đầu tiên. [Cần xác minh]'));
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Tôi đã đối chiếu, xác minh câu này', exact: true }).click();
  assert(!(await code.inputValue()).includes('[Cần xác minh]'));
  assert.equal(await page.getByLabel('Dạng câu 2', { exact: true }).inputValue(), 'essay');
  assert.equal(await page.getByRole('button', { name: 'Tôi đã đối chiếu, xác minh câu này', exact: true }).count(), 0);
  pass('Teacher verification clears evidence marker without an endless loop or silently changing essay grading');
  const save = page.waitForResponse(r => r.url().endsWith('/api/exam-drafts') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Lưu nháp', exact: true }).click();
  const saved = await (await save).json(); assert.equal(typeof saved.revision, 'number');
  const draftUrl = page.url();
  const refused = await context.request.post(`${base}/api/exam-drafts/${saved.id}/prepare`, { data: { revision: saved.revision } });
  assert.equal(refused.status(), 400); assert.match((await refused.json()).error.message, /tự luận/);
  const guest = await browser.newContext(); assert.equal((await guest.request.post(`${base}/api/exam-drafts/${saved.id}/prepare`, { data: { revision: saved.revision, excludeManual: true } })).status(), 401); await guest.close();
  pass('Backend independently blocks unsupported full exams and denies guests');
  for (const [name, width, theme, motion] of [['desktop-light', 1600, 'light', 'no-preference'], ['desktop-dark', 1600, 'dark', 'no-preference'], ['mobile-light', 375, 'light', 'no-preference'], ['mobile-dark-reduced', 375, 'dark', 'reduce']]) {
    await page.setViewportSize({ width, height: width < 600 ? 812 : 1100 });
    await page.emulateMedia({ colorScheme: theme, reducedMotion: motion });
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme; }, theme);
    await page.waitForTimeout(450);
    const size = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, viewport: innerWidth }));
    assert(size.width <= size.viewport + 1, `${name}: ${JSON.stringify(size)}`);
    if (motion === 'reduce') assert.equal(await page.locator('.exam-validation').evaluate(el => getComputedStyle(el).transitionDuration), '0s');
    await page.screenshot({ path: path.join(directory, `${name}.png`), fullPage: true }); pass(name);
  }
  await page.setViewportSize({ width: 1600, height: 1100 });
  await page.getByLabel('Chỉ duyệt phần chấm tự động', { exact: false }).check();
  page.once('dialog', dialog => dialog.accept());
  const preparation = page.waitForResponse(r => /\/api\/exam-drafts\/[^/]+\/prepare$/.test(r.url()));
  await page.getByRole('button', { name: 'Kiểm tra & duyệt đề →', exact: true }).click();
  const preparedResponse = await preparation; assert.equal(preparedResponse.status(), 200, await preparedResponse.text());
  const prepared = await preparedResponse.json(); assert.equal(prepared.questions.length, 1); assert.equal(prepared.excludedManualCount, 1); assert.equal(prepared.questions[0].reviewed, false);
  const preserved = await (await context.request.get(`${base}/api/exam-drafts/${saved.id}`)).json(); assert(preserved.code.includes('Máy tính đắt tiền.'));
  pass('Explicit automatic-only preparation keeps essay and answer in draft, without auto-review');
  await page.goto(draftUrl, { waitUntil: 'networkidle' });
  await page.getByLabel('Đáp án câu 2', { exact: true }).waitFor();
  page.once('dialog', dialog => dialog.accept());
  await page.getByLabel('Dạng câu 2', { exact: true }).selectOption('short');
  assert((await page.getByLabel('Đáp án câu 2', { exact: true }).inputValue()).includes('Máy tính rất lớn.'));
  assert.equal(await page.getByLabel('Dạng câu 2', { exact: true }).inputValue(), 'short');
  assert.equal(await essay.locator('.exam-card-status>span').innerText(), 'Sẵn sàng duyệt');
  const convertSave = page.waitForResponse(r => r.url().endsWith('/api/exam-drafts') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Lưu nháp', exact: true }).click(); await convertSave;
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.getByLabel('Dạng câu 2', { exact: true }).inputValue(), 'short');
  pass('Teacher-selected short-answer conversion preserves answer and survives real save/reload under essay heading');
  await code.fill('Câu 1: [type:short] Trả lời tên gọi?');
  const pending = page.getByLabel('Nội dung câu 1', { exact: true });
  await pending.fill('Nội dung mới chưa rời ô');
  await page.keyboard.press('Tab');
  await page.getByLabel('Đáp án câu 1', { exact: true }).fill('ENIAC | Eniac');
  const latestPrepare = page.waitForResponse(r => /\/api\/exam-drafts\/[^/]+\/prepare$/.test(r.url()));
  await page.getByRole('button', { name: 'Kiểm tra & duyệt đề →', exact: true }).click();
  const latestResponse = await latestPrepare; assert.equal(latestResponse.status(), 200, await latestResponse.text());
  const latest = (await latestResponse.json()).questions[0]; assert.equal(latest.stem, 'Nội dung mới chưa rời ô'); assert.deepEqual(latest.acceptedAnswers, ['ENIAC', 'Eniac']);
  pass('New answer and last edited visual body prepare immediately with latest values');
  assert.equal(errors.length, 0, errors.join('\n')); pass('No browser runtime errors');
} catch (error) {
  if (page) { await page.screenshot({ path: path.join(directory, 'failure.png'), fullPage: true }).catch(() => {}); await writeFile(path.join(directory, 'failure.txt'), await page.locator('body').innerText().catch(() => '')); }
  throw error;
} finally { await browser.close(); await writeFile(path.join(directory, 'results.json'), JSON.stringify({ checks, errors }, null, 2)); }